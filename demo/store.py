from typing import Protocol


class Storage(Protocol):
    def save(self, key: str, data: bytes) -> None: ...
    def load(self, key: str) -> bytes: ...


class Closer(Protocol):
    def close(self) -> None: ...


class FileStore:
    def save(self, key: str, data: bytes) -> None: ...
    def load(self, key: str) -> bytes: ...
    def close(self) -> None: ...


class MemoryStore:
    def save(self, key: str, data: bytes) -> None: ...
    def load(self, key: str) -> bytes: ...


class BrokenStore:
    # wrong type of key -> does not satisfy Storage
    def save(self, key: int, data: bytes) -> None: ...
    def load(self, key: int) -> bytes: ...


class Connection:
    def close(self) -> None: ...
